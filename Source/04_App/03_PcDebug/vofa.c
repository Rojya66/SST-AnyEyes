/*==================================================================
 * 函数功能: 按小端 IEEE754 组成最多十二通道的 JustFloat 帧，追加 00 00 80 7F 帧尾并提交队列
 * 输入参数: values：输入浮点波形通道数组，容量至少 count
 *           count：浮点通道数，最多 12
 * 输出参数: 协议工作标志、接收缓存及共享整帧发送队列；控制命令通过受控参数入口提交。
 * 返回值: 无；队列入队结果沿用原接口直接忽略
 * 执行说明: 主循环通信路径；AnyEyes/VOFA 由宏二选一，UART 收发有固定预算，不在 FPGA ISR 内打包或发送。
 *================================================================*/
static void VOFA_SendFloatArray(const float *values,unsigned short count)
{
 uint8_t frame[52]; /* frame：完整发送帧的本地字节缓存，包含帧头及校验。 */uint32_t word; /* word：通过 memcpy 得到的单通道 IEEE754 位表示，用于按小端逐字节打包。 */unsigned short i; /* i：本次数组、参数或模块遍历的索引。 */
 if(count>12) return;
 for(i=0;i<count;++i) {
  memcpy(&word,&values[i],4);
  frame[4*i]=(uint8_t)word;frame[4*i+1]=(uint8_t)(word>>8);
  frame[4*i+2]=(uint8_t)(word>>16);frame[4*i+3]=(uint8_t)(word>>24);
 }
 frame[4*count]=0;frame[4*count+1]=0;frame[4*count+2]=0x80;frame[4*count+3]=0x7F;
 SstSerial_SendFrame(frame,(uint16_t)(4*count+4));
}
