/*==================================================================
 * 函数名称: VOFA_SendFloatArray
 * 函数功能: 按小端 IEEE754 编码波形，并追加 JustFloat 帧尾。
 * 输入参数: values：浮点通道数组，至少包含 count 个元素。
 *           count：浮点通道数，范围 0～12；大于 12 时不发送。
 * 输出参数: 完整波形帧提交至共享串口发送队列；帧尾为 00 00 80 7F。
 * 返回值  : 无
 * 调用说明: 每通道占 4 字节，无额外帧头和校验；沿用原接口，不返回入队结果。
 *================================================================*/
static void VOFA_SendFloatArray(const float *values, unsigned short count)
{
    uint8_t frame[52]; /* 最多 12 个浮点载荷共 48 字节，加 4 字节帧尾。 */
    uint32_t word; /* 通过 memcpy 获取通道 IEEE754 位表示，供小端打包。 */
    unsigned short i; /* 浮点通道索引，范围为 0～count-1。 */
    if (count > 12)
        return;
    for (i = 0; i < count; ++i)
    {
        memcpy(&word, &values[i], 4);
        frame[4 * i] = (uint8_t)word;
        frame[4 * i + 1] = (uint8_t)(word >> 8);
        frame[4 * i + 2] = (uint8_t)(word >> 16);
        frame[4 * i + 3] = (uint8_t)(word >> 24);
    }
    /* JustFloat 固定帧尾：00 00 80 7F。 */
    frame[4 * count] = 0;
    frame[4 * count + 1] = 0;
    frame[4 * count + 2] = 0x80;
    frame[4 * count + 3] = 0x7F;
    SstSerial_SendFrame(frame, (uint16_t)(4 * count + 4));
}

/*==================================================================
 * 函数名称: VOFA_Send4Float
 * 函数功能: 按参数顺序提交 4 通道 JustFloat 波形。
 * 输入参数: a/b/c/d：依次对应通道 1～4；物理含义和单位由调用者确定。
 * 输出参数: 向共享串口发送队列提交一帧 20 字节的波形。
 * 返回值  : 无
 *================================================================*/
void VOFA_Send4Float(float a, float b, float c, float d)
{
    float x[4] = {a, b, c, d}; /* 按参数顺序排列的本次浮点通道数组。 */
    VOFA_SendFloatArray(x, 4);
}

